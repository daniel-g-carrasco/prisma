"""Generate application values; Casa keeps its own equivalent defaults."""
import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = ('space', 'radius', 'type', 'size', 'line', 'motion', 'layout', 'bar',
            'icon', 'stack', 'highlight', 'button')


def render(value):
    if value.get('format') != 2:
        raise ValueError('Expected style format 2')
    if set(value) != {'format', *SECTIONS}:
        raise ValueError('Missing or unexpected style sections')
    if not all(isinstance(value[key], dict) and value[key] for key in SECTIONS):
        raise ValueError('Empty or invalid scale')
    data = json.dumps({key: value[key] for key in SECTIONS}, sort_keys=True, ensure_ascii=True)
    return '# SPDX-License-Identifier: GPL-3.0-or-later\n"""Generated by tools/make_style.py."""\nFORMAT = 2\nSCALES_JSON = ' + repr(data) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    with (ROOT / 'style/tokens.toml').open('rb') as stream:
        source = render(tomllib.load(stream))
    package = next(p for p in (ROOT / 'src').iterdir() if (p / '__init__.py').is_file())
    target = package / 'gui/style/design_values.py'
    if args.check:
        if not target.is_file() or target.read_text(encoding='utf8') != source:
            print('Style differs: run tools/make_style.py', file=sys.stderr)
            return 1
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source, encoding='utf8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
